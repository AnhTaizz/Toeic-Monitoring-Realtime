package vn.edu.toeic.client.proctor.redesign;

import vn.edu.toeic.protocol.audio.ListeningStartRequest;
import vn.edu.toeic.protocol.audio.ListeningStartResponse;
import vn.edu.toeic.protocol.exam.rich.CreateRichSessionRequest;
import vn.edu.toeic.protocol.exam.rich.CreateRichSessionResponse;
import vn.edu.toeic.protocol.exam.rich.ExamCatalogPage;
import vn.edu.toeic.protocol.exam.rich.SessionReadiness;

/**
 * Blocking calls for the PROCTORED_V2 panel. {@link ProctorV2Controller} only calls them on its own workers,
 * never on the JavaFX Application Thread. Errors are {@code ProctorSessionApiClient.Rejected} (HTTP status) or I/O.
 */
interface ProctorV2Api extends AutoCloseable {
    /** {@code GET /api/v2/exams?limit=..&afterExamId=..}; {@code afterExamId} null for the first page. */
    ExamCatalogPage catalog(String afterExamId) throws Exception;

    /** {@code POST /api/v2/sessions}; sessionId and attemptIds are generated by the server. */
    CreateRichSessionResponse create(CreateRichSessionRequest request) throws Exception;

    /** {@code GET /api/v2/sessions/{id}/readiness}: audio + visual READY per attempt. */
    SessionReadiness readiness(String sessionId) throws Exception;

    /** {@code GET /api/v1/sessions/{id}/audio/readiness} → manifestId the START must name. */
    String audioManifest(String sessionId) throws Exception;

    /** {@code POST /api/v1/sessions/{id}/listening/start}: the only START; the server sets the deadline. */
    ListeningStartResponse start(String sessionId, ListeningStartRequest request) throws Exception;

    @Override void close();
}
