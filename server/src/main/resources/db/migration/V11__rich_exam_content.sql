-- V11: Rich TOEIC content matching the published 200-question HTML datasets.
--
-- Keep V5 columns for the current v1 import/read API.  The normalized tables below
-- represent shared question groups, ordered TEXT/IMAGE/AUDIO blocks, verified local
-- media and source/permission provenance without exposing scoring keys to clients.

-- A question order and an option order are identities inside an exam/question.
-- The V5 Java validator already rejects duplicate IDs; the database now also rejects
-- duplicate display positions and guarantees that correct_option really exists.
CREATE UNIQUE INDEX exam_questions_exam_order_unique
    ON exam_questions(exam_id, order_index);

CREATE UNIQUE INDEX exam_options_question_order_unique
    ON exam_options(exam_id, question_id, order_index);

ALTER TABLE exam_questions
    ADD CONSTRAINT exam_questions_section_part_consistent
        CHECK (
            (section = 'LISTENING' AND part BETWEEN 1 AND 4)
            OR (section = 'READING' AND part BETWEEN 5 AND 7)
        ),
    ADD CONSTRAINT exam_questions_correct_option_fk
        FOREIGN KEY (exam_id, question_id, correct_option)
        REFERENCES exam_options(exam_id, question_id, option_id)
        DEFERRABLE INITIALLY DEFERRED;

-- One source row records where an imported exam document came from and the exact
-- permission/checksum evidence used for that import.  Multiple source documents are
-- allowed because one exam can be assembled from separately licensed inputs.
CREATE TABLE exam_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id VARCHAR(128) NOT NULL REFERENCES exams(exam_id) ON DELETE CASCADE,
    source_name VARCHAR(255) NOT NULL,
    source_path VARCHAR(1024),
    source_url TEXT,
    copyright_notice TEXT,
    permission_status VARCHAR(24) NOT NULL
        CHECK (permission_status IN ('UNKNOWN', 'USER_CONFIRMED', 'DOCUMENTED', 'LICENSED')),
    permission_confirmed_on DATE,
    permission_note TEXT,
    license_document TEXT,
    answer_key_status VARCHAR(24) NOT NULL DEFAULT 'UNVERIFIED'
        CHECK (answer_key_status IN ('UNVERIFIED', 'VERIFIED')),
    group_mapping_status VARCHAR(24) NOT NULL DEFAULT 'UNVERIFIED'
        CHECK (group_mapping_status IN ('UNVERIFIED', 'VERIFIED')),
    media_validation_status VARCHAR(24) NOT NULL DEFAULT 'NOT_RUN'
        CHECK (media_validation_status IN ('NOT_RUN', 'PARTIAL', 'VERIFIED')),
    source_sha256 CHAR(64) NOT NULL CHECK (source_sha256 ~ '^[a-f0-9]{64}$'),
    manifest_sha256 CHAR(64) CHECK (manifest_sha256 ~ '^[a-f0-9]{64}$'),
    imported_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT exam_sources_exam_id_id_unique UNIQUE (exam_id, id),
    CONSTRAINT exam_sources_document_unique UNIQUE (exam_id, source_sha256),
    CONSTRAINT exam_sources_location_present CHECK (
        (source_path IS NOT NULL AND btrim(source_path) <> '')
        OR (source_url IS NOT NULL AND btrim(source_url) <> '')
    )
);

CREATE INDEX exam_sources_exam_idx ON exam_sources(exam_id);

-- Keep the source question number separate from runtime display order.  Provenance is
-- optional for legacy/API-v1 imports, but when present both values must be supplied.
ALTER TABLE exam_questions
    ADD COLUMN source_id BIGINT,
    ADD COLUMN source_question_number INT CHECK (source_question_number > 0),
    ADD COLUMN answer_key_status VARCHAR(24) NOT NULL DEFAULT 'UNVERIFIED'
        CHECK (answer_key_status IN ('UNVERIFIED', 'VERIFIED')),
    ADD CONSTRAINT exam_questions_source_pair CHECK (
        (source_id IS NULL AND source_question_number IS NULL)
        OR (source_id IS NOT NULL AND source_question_number IS NOT NULL)
    ),
    ADD CONSTRAINT exam_questions_source_fk
        FOREIGN KEY (exam_id, source_id) REFERENCES exam_sources(exam_id, id),
    ADD CONSTRAINT exam_questions_source_number_unique
        UNIQUE (exam_id, source_id, source_question_number);

-- Parts 3/4 share audio among question groups; Parts 6/7 share one or more ordered
-- passages/documents.  V5 only stored group_id as unchecked text, so backfill existing
-- groups before installing the foreign key.  A reused group with conflicting section
-- or part intentionally makes the migration fail instead of silently merging data.
CREATE TABLE exam_question_groups (
    exam_id VARCHAR(128) NOT NULL REFERENCES exams(exam_id) ON DELETE CASCADE,
    group_id VARCHAR(128) NOT NULL,
    section VARCHAR(32) NOT NULL CHECK (section IN ('LISTENING', 'READING')),
    part INT NOT NULL CHECK (part BETWEEN 1 AND 7),
    title VARCHAR(255),
    order_index INT NOT NULL CHECK (order_index > 0),
    mapping_status VARCHAR(24) NOT NULL DEFAULT 'UNVERIFIED'
        CHECK (mapping_status IN ('UNVERIFIED', 'VERIFIED')),
    PRIMARY KEY (exam_id, group_id),
    CONSTRAINT exam_question_groups_exam_order_unique UNIQUE (exam_id, order_index),
    CONSTRAINT exam_question_groups_section_part_consistent CHECK (
        (section = 'LISTENING' AND part BETWEEN 1 AND 4)
        OR (section = 'READING' AND part BETWEEN 5 AND 7)
    )
);

-- V5 treated a blank group ID like "no group" in validation but still persisted the
-- raw value.  Normalize that legacy representation before installing the foreign key.
UPDATE exam_questions
SET group_id = NULL
WHERE group_id IS NOT NULL AND btrim(group_id) = '';

INSERT INTO exam_question_groups(exam_id, group_id, section, part, order_index)
SELECT exam_id, group_id, section, part, MIN(order_index)
FROM exam_questions
WHERE group_id IS NOT NULL AND btrim(group_id) <> ''
GROUP BY exam_id, group_id, section, part;

ALTER TABLE exam_questions
    ADD CONSTRAINT exam_questions_group_fk
        FOREIGN KEY (exam_id, group_id)
        REFERENCES exam_question_groups(exam_id, group_id);

-- Binary data stays outside PostgreSQL.  A REMOTE_REFERENCE row is inventory only;
-- LOCAL_VERIFIED is usable runtime media and therefore requires MIME, byte length,
-- SHA-256 and a relative local file name.  Images may store intrinsic dimensions;
-- audio may store duration when known.
CREATE TABLE exam_media_assets (
    exam_id VARCHAR(128) NOT NULL REFERENCES exams(exam_id) ON DELETE CASCADE,
    media_id VARCHAR(128) NOT NULL,
    media_type VARCHAR(16) NOT NULL CHECK (media_type IN ('IMAGE', 'AUDIO')),
    source_id BIGINT,
    source_url TEXT,
    storage_status VARCHAR(24) NOT NULL
        CHECK (storage_status IN ('REMOTE_REFERENCE', 'LOCAL_VERIFIED')),
    local_file VARCHAR(255),
    mime_type VARCHAR(127),
    size_bytes BIGINT CHECK (size_bytes IS NULL OR size_bytes >= 0),
    sha256 CHAR(64) CHECK (sha256 IS NULL OR sha256 ~ '^[a-f0-9]{64}$'),
    width_px INT CHECK (width_px IS NULL OR width_px > 0),
    height_px INT CHECK (height_px IS NULL OR height_px > 0),
    duration_ms BIGINT CHECK (duration_ms IS NULL OR duration_ms > 0),
    alt_text TEXT,
    PRIMARY KEY (exam_id, media_id),
    CONSTRAINT exam_media_assets_typed_identity UNIQUE (exam_id, media_id, media_type),
    CONSTRAINT exam_media_assets_source_fk
        FOREIGN KEY (exam_id, source_id) REFERENCES exam_sources(exam_id, id),
    CONSTRAINT exam_media_assets_verified_complete CHECK (
        storage_status <> 'LOCAL_VERIFIED'
        OR (local_file IS NOT NULL AND btrim(local_file) <> ''
            AND mime_type IS NOT NULL AND btrim(mime_type) <> ''
            AND size_bytes IS NOT NULL AND sha256 IS NOT NULL)
    ),
    CONSTRAINT exam_media_assets_dimensions_by_type CHECK (
        media_type = 'IMAGE' OR (width_px IS NULL AND height_px IS NULL)
    ),
    CONSTRAINT exam_media_assets_duration_by_type CHECK (
        media_type = 'AUDIO' OR duration_ms IS NULL
    )
);

CREATE UNIQUE INDEX exam_media_assets_local_file_unique
    ON exam_media_assets(exam_id, local_file)
    WHERE local_file IS NOT NULL;

-- A block belongs to exactly one question or one shared group.  TEXT stores sanitized
-- plain content; IMAGE/AUDIO points at a same-typed asset.  Partial unique indexes keep
-- deterministic order independently for each owner.
CREATE TABLE exam_content_blocks (
    exam_id VARCHAR(128) NOT NULL REFERENCES exams(exam_id) ON DELETE CASCADE,
    block_id VARCHAR(128) NOT NULL,
    group_id VARCHAR(128),
    question_id VARCHAR(128),
    block_type VARCHAR(16) NOT NULL CHECK (block_type IN ('TEXT', 'IMAGE', 'AUDIO')),
    order_index INT NOT NULL CHECK (order_index > 0),
    text_content TEXT,
    media_id VARCHAR(128),
    media_type VARCHAR(16),
    PRIMARY KEY (exam_id, block_id),
    CONSTRAINT exam_content_blocks_one_owner CHECK (
        (group_id IS NOT NULL AND question_id IS NULL)
        OR (group_id IS NULL AND question_id IS NOT NULL)
    ),
    CONSTRAINT exam_content_blocks_payload CHECK (
        (block_type = 'TEXT' AND text_content IS NOT NULL AND btrim(text_content) <> ''
            AND media_id IS NULL AND media_type IS NULL)
        OR (block_type IN ('IMAGE', 'AUDIO') AND text_content IS NULL
            AND media_id IS NOT NULL AND media_type = block_type)
    ),
    CONSTRAINT exam_content_blocks_group_fk
        FOREIGN KEY (exam_id, group_id)
        REFERENCES exam_question_groups(exam_id, group_id) ON DELETE CASCADE,
    CONSTRAINT exam_content_blocks_question_fk
        FOREIGN KEY (exam_id, question_id)
        REFERENCES exam_questions(exam_id, question_id) ON DELETE CASCADE,
    CONSTRAINT exam_content_blocks_media_fk
        FOREIGN KEY (exam_id, media_id, media_type)
        REFERENCES exam_media_assets(exam_id, media_id, media_type)
);

CREATE UNIQUE INDEX exam_content_blocks_group_order_unique
    ON exam_content_blocks(exam_id, group_id, order_index)
    WHERE group_id IS NOT NULL;

CREATE UNIQUE INDEX exam_content_blocks_question_order_unique
    ON exam_content_blocks(exam_id, question_id, order_index)
    WHERE question_id IS NOT NULL;

CREATE INDEX exam_content_blocks_media_idx
    ON exam_content_blocks(exam_id, media_id)
    WHERE media_id IS NOT NULL;
